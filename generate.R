#!/usr/bin/env Rscript
# generate.R -- builds the "compiled law" book sources from enacted CRs.
#
# Run from the ecl/ project directory (e.g. as a Quarto pre-render script):
#   project:
#     pre-render: Rscript scripts/generate.R
#
# Output:
#   title<N>/<slug>.qmd       one file per Act   (params.creates / amends / repeals)
#   title<N>/reg-<slug>.qmd   one file per Act's regulations (params.regulates)
#   _chapters.yml             book chapter list (pull in via `metadata-files`)
# <N> comes from params.title in the CRs.
#
# A CR is included only if params.dates.assent is set and its effective date
# (params.dates.effective, or the assent date if none) is on or before the
# as-of date (today, or the COMPILE_AS_OF env var, e.g. COMPILE_AS_OF=2026-07-01).
#
# Each section version is written with literal attributes:
#   ## Sec. 1.001 --- Title. {#sec-2026-as-1-1-001 date="2025-03-14" cr="26CR2" chapter="..."}
# The stable #id is only written on the winning (latest) version of each section.
# latest-section.lua then drops superseded versions, sorts, and adds chapter
# headings and "Source:" notes.

suppressPackageStartupMessages(library(yaml))

# ---- Configuration --------------------------------------------------------
CFG <- list(
  res_dir       = "../resolutions",
  out_dir       = ".",
  head_rx       = "^\\s*\\{\\{<\\s*include\\s+_res-head\\.qmd\\s*>\\}\\}\\s*$",
  chapter_level = 1L,   # heading level of "Chapter" headings in CRs
  section_level = 2L,   # heading level of "Sec." headings (normalized on output)
  range_sep     = "\\.\\.\\.",  # between the section numbers in the sidebar label ("\\.\\.\\." = literal "...")
  # URL from an Act page (ecl/title1/x.html) to the resolutions book, for History links.
  # Assumes the books are mounted side by side: <site>/ecl/ and <site>/resolutions/.
  cr_base       = "../../resolutions",
  titles_file   = "titles.yml",  # static file: Title number -> Title name
  title_sep     = "\u2014",      # "Title 1 <sep> General Provisions"
  enactment_clause = "Be It Enacted By The Crown-In-Council:",
  strict        = TRUE, # any ERROR aborts before anything is written
  as_of         = Sys.getenv("COMPILE_AS_OF", format(Sys.Date(), "%Y-%m-%d"))
)

GEN_MARK <- "<!-- generated by generate.R: do not edit -->"

# ---- Logging / validation helpers -----------------------------------------
n_errors <- 0L
err  <- function(...) { n_errors <<- n_errors + 1L; message("ERROR: ", ...) }
warn <- function(...) message("WARNING: ", ...)

valid_date <- function(d) {
  is.character(d) && length(d) == 1L && !is.na(d) &&
    grepl("^[0-9]{4}-[0-9]{2}-[0-9]{2}$", d) &&
    !is.na(as.Date(d, format = "%Y-%m-%d"))
}

as_ids <- function(x) {
  x <- trimws(as.character(unlist(x, use.names = FALSE)))
  x <- gsub("\\s+", " ", x)
  x[nzchar(x)]
}

# first non-empty value as a trimmed string, else NA
scalar_chr <- function(x) {
  x <- as.character(unlist(x, use.names = FALSE))
  if (!length(x) || is.na(x[1]) || !nzchar(trimws(x[1]))) NA_character_ else trimws(x[1])
}

# "26CR10" sorts after "26CR2"; "2026 AS 10" after "2026 AS 2"
nat_key <- function(s) {
  n <- as.integer(regmatches(s, gregexpr("[0-9]+", s))[[1]])
  paste(c(sprintf("%08d", n), s), collapse = "-")
}

slugify <- function(x) gsub("^-+|-+$", "", gsub("[^a-z0-9]+", "-", tolower(x)))
# Quarto skips markdown processing of a sidebar/part label containing a bare "&",
# so write it as an entity (already-encoded entities are left alone).
amp_fix <- function(x) gsub("&(?![A-Za-z]+;|#[0-9]+;)", "&amp;", x, perl = TRUE)

load_titles <- function() {
  f <- file.path(CFG$out_dir, CFG$titles_file)
  if (!file.exists(f)) {
    warn(CFG$titles_file, " not found; Titles will be labelled by number only")
    return(character())
  }
  y <- tryCatch(yaml::yaml.load_file(f), error = function(e) {
    err(f, ": YAML parse failed: ", conditionMessage(e)); NULL })
  if (!is.list(y) || !length(y)) return(character())
  setNames(trimws(as.character(unlist(y, use.names = FALSE))), as.character(names(y)))
}

yaml_str <- function(x) paste0('"', gsub('"', '\\\\"', gsub("\\\\", "\\\\\\\\", x)), '"')
esc_attr <- function(x) gsub('"', '\\\\"', x)
stub_body <- function(cr_title) sprintf("*\\[Repealed by %s\\]*", cr_title)

# ---- Reading a CR ----------------------------------------------------------
read_cr <- function(path) {
  lines <- readLines(path, warn = FALSE, encoding = "UTF-8")
  if (length(lines) < 3L || trimws(lines[1]) != "---") return(NULL)
  close <- which(trimws(lines[-1]) %in% c("---", "..."))[1] + 1L
  if (is.na(close) || close == 2L) return(NULL)

  meta <- tryCatch(
    yaml::yaml.load(paste(lines[2:(close - 1L)], collapse = "\n")),
    error = function(e) {
      err(path, ": YAML parse failed: ", conditionMessage(e)); NULL
    })
  if (!is.list(meta) || is.null(meta$params)) return(NULL)

  body <- if (close < length(lines)) lines[(close + 1L):length(lines)] else character()
  head_at <- which(grepl(CFG$head_rx, body))[1]
  has_head <- !is.na(head_at)
  p <- meta$params

  list(
    file = sub(paste0("^", CFG$res_dir, "/"), "", path, fixed = FALSE),
    title = if (is.null(meta$title)) NA_character_ else as.character(meta$title)[1],
    assent = scalar_chr(p$dates$assent),
    effective = scalar_chr(p$dates$effective),
    title_n = scalar_chr(p$title),
    short_title = scalar_chr(p$short_title),
    enacted_title = scalar_chr(p$enacted_title),
    enacted_as = { x <- scalar_chr(p$enacted_as); if (is.na(x)) x else gsub("\\s+", " ", x) },
    creates = as_ids(p$creates), amends = as_ids(p$amends),
    regulates = as_ids(p$regulates), repeals = as_ids(p$repeals),
    has_head = has_head,
    body = if (!has_head) character()
           else if (head_at < length(body)) body[(head_at + 1L):length(body)]
           else character()
  )
}

# ---- Extracting sections from a CR body -------------------------------------
split_attrs <- function(raw) {
  # trailing {...} attribute block; tolerates {{< shortcodes >}} inside it
  rx <- "\\s*\\{(?:[^{}]|\\{\\{<[^}]*>\\}\\})*\\}\\s*$"
  pos <- regexpr(rx, raw, perl = TRUE)
  if (pos == -1L) return(list(text = trimws(raw), attrs = ""))
  list(text = trimws(substr(raw, 1L, pos - 1L)), attrs = trimws(substring(raw, pos)))
}

parse_sections <- function(lines, cr_title) {
  secs <- list(); cur <- NULL; chapter <- NULL; orphans <- 0L; in_fence <- FALSE

  close_cur <- function() {
    if (is.null(cur)) return(invisible())
    while (length(cur$body) && !nzchar(trimws(cur$body[length(cur$body)]))) {
      cur$body <<- cur$body[-length(cur$body)]
    }
    secs[[length(secs) + 1L]] <<- cur
    cur <<- NULL
  }

  for (ln in lines) {
    if (grepl("^\\s*(```|~~~)", ln)) in_fence <- !in_fence
    m <- if (in_fence) character()
         else regmatches(ln, regexec("^(#{1,6})\\s+(.*?)\\s*$", ln, perl = TRUE))[[1]]

    if (length(m) == 3L) {
      level <- nchar(m[2]); sp <- split_attrs(m[3])
      num <- sub("^Sec\\.?\\s+([0-9.]+).*$", "\\1", sp$text)
      is_sec <- grepl("^Sec\\.?\\s+[0-9]", sp$text)

      if (is_sec) {
        close_cur()
        if (level != CFG$section_level) {
          warn(cr_title, ": '", sp$text, "' is heading level ", level,
               "; normalizing to ", CFG$section_level)
        }
        st <- sub('^.*status\\s*=\\s*"?([A-Za-z-]+)"?.*$', "\\1", sp$attrs)
        cur <- list(
          num = sub("\\.$", "", num), text = sp$text,
          status = if (grepl("status\\s*=", sp$attrs)) tolower(st) else "",
          chapter = chapter, body = character()
        )
      } else if (level <= CFG$chapter_level) {
        close_cur(); chapter <- sp$text
      } else if (level <= CFG$section_level) {
        close_cur()
        warn(cr_title, ": heading '", sp$text, "' is neither a chapter nor a Sec.; ",
             "its content will be ignored")
        orphans <- orphans + 1L
      } else if (!is.null(cur)) {
        cur$body <- c(cur$body, ln)       # sub-heading inside a section
      } else orphans <- orphans + 1L
    } else if (!is.null(cur)) {
      cur$body <- c(cur$body, ln)
    } else if (nzchar(trimws(ln))) {
      orphans <- orphans + 1L
    }
  }
  close_cur()

  if (orphans > 0L) {
    warn(cr_title, ": ", orphans, " non-blank line(s) outside any 'Sec.' block were ignored")
  }
  secs
}

# ---- Compiling one instrument ----------------------------------------------
render_section <- function(v, slug) {
  attrs <- character()
  if (isTRUE(v$winner)) {
    attrs <- c(attrs, paste0("#sec-", slug, "-", gsub("\\.", "-", v$num)))
  }
  attrs <- c(attrs, sprintf('date="%s"', v$date), sprintf('cr="%s"', esc_attr(v$cr)))
  if (!is.null(v$enacted_as)) attrs <- c(attrs, sprintf('enacted-as="%s"', esc_attr(v$enacted_as)))
  if (isTRUE(v$imd)) attrs <- c(attrs, 'imd="true"')
  if (!is.null(v$cr_file)) {
    href <- paste0(CFG$cr_base, "/", sub("\\.qmd$", ".html", v$cr_file))
    attrs <- c(attrs, sprintf('cr-href="%s"', esc_attr(href)))
  }
  if (!is.null(v$chapter)) attrs <- c(attrs, sprintf('chapter="%s"', esc_attr(v$chapter)))
  if (identical(v$status, "repealed")) attrs <- c(attrs, 'status="repealed"')
  c("", paste0(strrep("#", CFG$section_level), " ", v$text, " {",
               paste(attrs, collapse = " "), "}"),
    "", v$body)
}

compile_instrument <- function(inst) {
  label <- paste(inst$kind, inst$id)
  entries <- inst$entries
  entries <- entries[order(
    vapply(entries, function(e) e$cr$date, ""),
    vapply(entries, function(e) nat_key(e$cr$title), "")
  )]

  roles <- vapply(entries, function(e) e$role, "")
  titles <- vapply(entries, function(e) e$cr$title, "")
  for (d in unique(titles[duplicated(titles)])) {
    err(label, ": CR ", d, " lists this instrument in more than one params field")
  }
  if (inst$kind == "act") {
    if (!("create" %in% roles)) {
      warn(label, ": no CR has params.creates for it (found only: ",
           paste(unique(roles), collapse = ", "), ")")
    } else if (roles[1] != "create") {
      warn(label, ": earliest CR (", titles[1], ") is a '", roles[1],
           "', not the creating CR")
    }
  }

  versions <- list(); known <- list(); n <- 0L
  add_version <- function(v) {
    n <<- n + 1L; v$ord <- n
    versions[[n]] <<- v
    known[[v$num]] <<- v
  }

  for (e in entries) {
    cr <- e$cr
    if (e$role == "repeal") {
      if (any(grepl("^#{1,6}\\s+Sec\\.?\\s", cr$body))) {
        warn(cr$title, ": repeals ", inst$id, "; its Sec. content is ignored")
      }
      if (length(known) == 0L) {
        warn(cr$title, ": repeals ", inst$id, " but no earlier CR supplies any sections")
      }
      for (num in names(known)) {
        prev <- known[[num]]
        if (identical(prev$status, "repealed")) next
        v <- prev
        v$status <- "repealed"; v$cr <- cr$title; v$date <- cr$date
        v$enacted_as <- cr$enacted_as; v$imd <- cr$imd; v$cr_file <- cr$file
        v$body <- stub_body(cr$title)
        add_version(v)
      }
    } else {
      if (!cr$has_head) {
        err(cr$file, ": no '{{< include _res-head.qmd >}}' line found")
        next
      }
      secs <- parse_sections(cr$body, cr$title)
      if (length(secs) == 0L) warn(cr$title, ": no 'Sec.' headings found")
      seen <- character()
      for (s in secs) {
        if (s$num %in% seen) err(cr$title, ": Sec. ", s$num, " appears more than once")
        seen <- c(seen, s$num)
        s$cr <- cr$title; s$date <- cr$date; s$imd <- cr$imd; s$cr_file <- cr$file
        s$enacted_as <- if (e$role == "create") inst$id else cr$enacted_as
        # a CR that omits the chapter heading inherits the section's earlier chapter
        if (is.null(s$chapter) && !is.null(known[[s$num]])) s$chapter <- known[[s$num]]$chapter
        if (identical(s$status, "repealed")) s$body <- stub_body(cr$title)
        add_version(s)
      }
    }
  }
  if (n == 0L) return(NULL)

  # winners: latest date; ties go to the later CR (matches the Lua filter)
  nums <- vapply(versions, function(v) v$num, "")
  lead <- sub("\\..*$", "", nums)
  for (num in unique(nums[lead != inst$title_n])) {
    err(label, ": Sec. ", num, " does not belong in Title ", inst$title_n,
        " (from params.title)")
  }
  for (num in unique(nums)) {
    idx <- which(nums == num)
    ds <- vapply(versions[idx], function(v) v$date, "")
    top <- idx[ds == max(ds)]
    tc <- unique(vapply(versions[top], function(v) v$cr, ""))
    if (length(tc) > 1L) {
      warn(label, " Sec. ", num, ": CRs ", paste(tc, collapse = ", "),
           " share date ", max(ds), "; the later one in CR order wins")
    }
    versions[[max(top)]]$winner <- TRUE
  }

  # Act files are titled with params.short_title of the (earliest) creating CR
  title <- if (inst$kind == "reg") paste("Regulations under", inst$id) else inst$id
  if (inst$kind == "act") {
    creators <- entries[roles == "create"]
    if (length(creators) > 1L) {
      warn(label, ": created by more than one CR (",
           paste(titles[roles == "create"], collapse = ", "), "); using ", titles[roles == "create"][1])
    }
    if (length(creators) && !is.na(creators[[1]]$cr$short_title)) {
      title <- creators[[1]]$cr$short_title
    } else if (length(creators)) {
      warn(label, ": creating CR ", creators[[1]]$cr$title,
           " has no params.short_title; falling back to '", title, "'")
    }
  }
  body <- unlist(lapply(versions, render_section, slug = inst$slug))

  # Preamble (Acts only): the creating CR's params.enacted_title, then the enacting clause.
  # Styled via .enacted-title / .enactment-clause in law.css.
  preamble <- character()
  if (inst$kind == "act") {
    et <- if (length(creators)) creators[[1]]$cr$enacted_title else NA_character_
    if (is.na(et) && length(creators)) {
      warn(label, ": creating CR ", creators[[1]]$cr$title, " has no params.enacted_title")
    }
    if (!is.na(et)) preamble <- c(preamble, "::: {.enacted-title}", et, ":::", "")
    preamble <- c(preamble, "::: {.enactment-clause}", CFG$enactment_clause, ":::", "")
  }

  # Sidebar label for Acts: "Title (first ... last)", over every section in the Act
  # (repealed stubs included, since they are displayed).
  uniq <- unique(nums)
  uniq <- uniq[order(vapply(uniq, nat_key, ""))]
  label <- title
  if (inst$kind == "act") {
    label <- if (length(uniq) == 1L) sprintf("%s (%s)", title, uniq)
             else sprintf("%s (%s %s %s)", title, uniq[1], CFG$range_sep, uniq[length(uniq)])
  }
  # Quarto skips markdown processing of a sidebar label containing a bare "&",
  # so write it as an entity (already-encoded entities are left alone).
  label <- amp_fix(label)
  # Acts carry their ID in a <meta> tag; act-breadcrumb.html uses it to rewrite the breadcrumb.
  hdr <- if (inst$kind == "act") {
    c("include-in-header:",
      paste0("  text: ", yaml_str(sprintf('<meta name="act-id" content="%s">', inst$id))))
  } else character()

  list(label = label,
       text = c("---",
                paste0("title: ", yaml_str(title)),
                sprintf('instrument: "%s"', inst$id),
                sprintf('instrument-slug: "%s"', inst$slug),
                sprintf("instrument-kind: %s", inst$kind),
                sprintf("instrument-title: %s", inst$title_n),
                hdr,
                "---", "", GEN_MARK, "", preamble, body, ""))
}

# ---- Output ------------------------------------------------------------------
clean_generated <- function(dir) {
  if (!dir.exists(dir)) return(invisible())
  for (f in list.files(dir, "\\.qmd$", full.names = TRUE)) {
    if (any(grepl(GEN_MARK, readLines(f, n = 15, warn = FALSE), fixed = TRUE))) file.remove(f)
  }
}

write_chapters <- function(done, titles) {
  L <- c("book:", "  chapters:", "    - index.qmd")
  tn <- sort(unique(as.integer(vapply(done, function(d) d$title_n, ""))))
  for (t in tn) {
    sel <- Filter(function(d) as.integer(d$title_n) == t, done)  # acts first, then regs
    nm <- titles[as.character(t)]
    if (is.na(nm) || !nzchar(nm)) {
      warn("no name for Title ", t, " in ", CFG$titles_file, "; using 'Title ", t, "'")
      plabel <- sprintf("Title %d", t)
    } else {
      plabel <- sprintf("Title %d %s %s", t, CFG$title_sep, nm)
    }
    L <- c(L, paste0("    - part: ", yaml_str(amp_fix(plabel))), "      chapters:",
           unlist(lapply(sel, function(d)
             c(sprintf("        - href: %s/%s.qmd", d$dir, d$slug),
               paste0("          text: ", yaml_str(d$label))))))
  }
  writeLines(enc2utf8(L), file.path(CFG$out_dir, "_chapters.yml"), useBytes = TRUE)
}

# ---- Main --------------------------------------------------------------------
main <- function() {
  # Recurse into year folders (resolutions/2026/26CR2.qmd). The pattern is matched
  # against the file name, so _res-head.qmd and other _*.qmd files are skipped;
  # any folder starting with "_" or "." (e.g. _book, .quarto) is skipped too.
  files <- list.files(CFG$res_dir, pattern = "^[^_].*\\.qmd$",
                      recursive = TRUE, full.names = FALSE)
  files <- files[!grepl("(^|/)[_.]", files)]
  files <- file.path(CFG$res_dir, files)
  all_crs <- Filter(Negate(is.null), lapply(files, read_cr))
  if (!valid_date(CFG$as_of)) stop("as-of date is not YYYY-MM-DD: ", CFG$as_of)
  crs <- Filter(function(cr) !is.na(cr$assent), all_crs)   # assent = enacted
  message(sprintf("Found %d CR file(s); %d assented. Compiling as of %s.",
                  length(all_crs), length(crs), CFG$as_of))

  good <- list(); pending <- 0L
  for (cr in crs) {
    label <- if (is.na(cr$title)) cr$file else cr$title
    if (is.na(cr$title) || !nzchar(cr$title)) { err(cr$file, ": missing 'title'"); next }
    if (!valid_date(cr$assent)) {
      err(label, ": params.dates.assent is not a valid YYYY-MM-DD date (", cr$assent, ")")
      next
    }
    if (!is.na(cr$effective) && !valid_date(cr$effective)) {
      err(label, ": params.dates.effective is not a valid YYYY-MM-DD date (", cr$effective, ")")
      next
    }
    # version date = effective date; falls back to assent
    # imd = immediate effect: no effective date, or it equals the assent date
    if (is.na(cr$effective)) {
      cr$date <- cr$assent; cr$imd <- TRUE
    } else if (cr$effective < cr$assent) {
      warn(label, ": effective date ", cr$effective, " is before assent ", cr$assent,
           "; using the assent date")
      cr$date <- cr$assent; cr$imd <- TRUE
    } else {
      cr$date <- cr$effective; cr$imd <- (cr$effective == cr$assent)
    }
    if (is.na(cr$title_n) || !grepl("^[0-9]+$", cr$title_n)) {
      err(label, ": params.title must be a whole number (the Title)"); next
    }
    cr$title_n <- as.character(as.integer(cr$title_n))
    ids <- c(cr$creates, cr$amends, cr$regulates, cr$repeals)
    if (!length(ids)) {
      warn(label, ": assented but has none of creates/amends/regulates/repeals; skipped")
      next
    }
    # params.enacted_as: this CR's own Act/Order number. For a creating CR it
    # should equal params.creates (and is otherwise not needed).
    if (is.na(cr$enacted_as)) {
      if (length(cr$creates) == 1L) {
        cr$enacted_as <- cr$creates
      } else {
        err(label, ": params.enacted_as is required (this CR does not create exactly one Act)")
        next
      }
    } else if (length(cr$creates) == 1L && cr$enacted_as != cr$creates) {
      warn(label, ": params.enacted_as (", cr$enacted_as, ") differs from params.creates (",
           cr$creates, "); '", cr$creates, "' is used for the Act's \"Add.\" entry")
    }
    if (cr$date > CFG$as_of) {
      pending <- pending + 1L
      message(sprintf("  %s: assented %s, not effective until %s; excluded.",
                      label, cr$assent, cr$date))
      next
    }
    all_ids <- c(ids, cr$enacted_as)
    bad <- all_ids[!grepl("^[0-9]{4} [A-Z]+ [0-9]+$", all_ids)]
    if (length(bad)) warn(label, ": unusual Act/Order number(s): ", paste(unique(bad), collapse = ", "))
    good[[length(good) + 1L]] <- cr
  }
  message(sprintf("%d in effect, %d pending.", length(good), pending))
  tt <- vapply(good, function(cr) cr$title, "")
  for (d in unique(tt[duplicated(tt)])) err("duplicate CR title: ", d)

  insts <- list()
  reg <- function(kind, id, cr, role) {
    key <- paste(kind, id)
    if (!is.null(insts[[key]]) && insts[[key]]$title_n != cr$title_n) {
      err(key, ": CRs disagree on params.title (", insts[[key]]$title_n, " vs ",
          cr$title_n, " in ", cr$title, ")")
    }
    if (is.null(insts[[key]])) {
      insts[[key]] <<- list(
        kind = kind, id = id, title_n = cr$title_n, dir = paste0("title", cr$title_n),
        slug = if (kind == "act") slugify(id) else paste0("reg-", slugify(id)),
        entries = list())
    }
    insts[[key]]$entries[[length(insts[[key]]$entries) + 1L]] <<- list(cr = cr, role = role)
  }
  for (cr in good) {
    for (id in cr$creates)   reg("act", id, cr, "create")
    for (id in cr$amends)    reg("act", id, cr, "amend")
    for (id in cr$repeals)   reg("act", id, cr, "repeal")
    for (id in cr$regulates) reg("reg", id, cr, "regulate")
  }
  insts <- insts[order(vapply(insts, function(i) i$kind, ""),
                       vapply(insts, function(i) nat_key(i$id), ""))]

  compiled <- list(); done <- list()
  for (inst in insts) {
    res <- compile_instrument(inst)
    if (!is.null(res)) {
      compiled[[inst$slug]] <- res$text
      inst$label <- res$label
      done[[length(done) + 1L]] <- inst
    }
  }

  titles <- load_titles()

  if (n_errors > 0L && CFG$strict) {
    message(sprintf("\n%d error(s); nothing written.", n_errors))
    quit(status = 1L, save = "no")
  }

  dirs <- list.dirs(CFG$out_dir, recursive = FALSE, full.names = TRUE)
  for (d in dirs[grepl("^title[0-9]+$", basename(dirs))]) clean_generated(d)
  for (inst in done) {
    dir.create(file.path(CFG$out_dir, inst$dir), showWarnings = FALSE, recursive = TRUE)
    writeLines(compiled[[inst$slug]],
               file.path(CFG$out_dir, inst$dir, paste0(inst$slug, ".qmd")), useBytes = TRUE)
  }
  write_chapters(done, titles)
  message(sprintf("Wrote %d instrument file(s).", length(done)))
}

